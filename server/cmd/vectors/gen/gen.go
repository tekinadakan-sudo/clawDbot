// Package gen produces the Kilit protocol test vectors of docs/DESIGN.md §3.8
// in the §3.9 file schemas, from the Go reference implementation in
// pkg/kilitcrypto. Every value is a deterministic function of the fixed seeds
// of §3.8: no clock, no randomness. cmd/vectors is the command-line front
// end; the golden test in pkg/kilitcrypto regenerates through Generate and
// fails on any byte difference from the committed files.
package gen

import (
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	kc "github.com/tekinadakan-sudo/clawDbot/server/pkg/kilitcrypto"
)

// MaxFileBytes is the §3.8 cap on every output file.
const MaxFileBytes = 200 * 1024

// forbidden is the sequence that would terminate the Swift raw literal.
const forbidden = `"""#`

// Set is one vector set: its JSON file, its Swift file and the static
// property name of the KilitVectors extension.
type Set struct {
	JSONFile  string
	SwiftFile string
	Name      string
}

// Sets lists the nine sets in the order of §3.8.
var Sets = []Set{
	{"primitives.json", "KilitVectors+Primitives.swift", "primitives"},
	{"base64url.json", "KilitVectors+Base64url.swift", "base64url"},
	{"x3dh_session.json", "KilitVectors+X3DH.swift", "x3dh"},
	{"ratchet_conversation.json", "KilitVectors+Ratchet.swift", "ratchet"},
	{"ratchet_eviction.json", "KilitVectors+Eviction.swift", "eviction"},
	{"attachment.json", "KilitVectors+Attachment.swift", "attachment"},
	{"envelope.json", "KilitVectors+Envelope.swift", "envelope"},
	{"safety.json", "KilitVectors+Safety.swift", "safety"},
	{"watermark.json", "KilitVectors+Watermark.swift", "watermark"},
}

// SwiftRootFile declares the empty enum the extensions hang off.
const SwiftRootFile = "KilitVectors.swift"

// Files is the complete generator output, keyed by file name.
type Files struct {
	JSON  map[string][]byte
	Swift map[string][]byte
}

// Generate builds every file in memory. Internal self-checks (RFC constants,
// expected errors, symmetry) panic; Generate turns a panic into an error.
func Generate() (f *Files, err error) {
	defer func() {
		if r := recover(); r != nil {
			err = fmt.Errorf("vectors: %v", r)
		}
	}()
	x := buildSetA()
	docs := map[string]any{
		"primitives.json":           primitives(),
		"base64url.json":            base64urlSet(),
		"x3dh_session.json":         x.doc,
		"ratchet_conversation.json": ratchetConversation(x),
		"ratchet_eviction.json":     ratchetEviction(x),
		"attachment.json":           attachmentSet(),
		"envelope.json":             envelopeSet(x),
		"safety.json":               safetySet(x),
		"watermark.json":            watermarkSet(x),
	}
	f = &Files{JSON: map[string][]byte{}, Swift: map[string][]byte{}}
	for _, s := range Sets {
		js := encodeJSON(docs[s.JSONFile])
		if bytes.Contains(js, []byte(forbidden)) {
			return nil, fmt.Errorf("vectors: %s contains %s", s.JSONFile, forbidden)
		}
		sw := swiftLiteral(s.Name, js)
		for name, b := range map[string][]byte{s.JSONFile: js, s.SwiftFile: sw} {
			if len(b) > MaxFileBytes {
				return nil, fmt.Errorf("vectors: %s is %d bytes, over the %d-byte cap", name, len(b), MaxFileBytes)
			}
		}
		f.JSON[s.JSONFile] = js
		f.Swift[s.SwiftFile] = sw
	}
	f.Swift[SwiftRootFile] = []byte(swiftHeader + "enum KilitVectors {}\n")
	return f, nil
}

// Write generates and writes the files into outDir (JSON) and swiftDir
// (Swift), creating the directories. It returns the size of every file.
func Write(outDir, swiftDir string) (map[string]int, error) {
	f, err := Generate()
	if err != nil {
		return nil, err
	}
	sizes := map[string]int{}
	for dir, files := range map[string]map[string][]byte{outDir: f.JSON, swiftDir: f.Swift} {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return nil, err
		}
		for name, b := range files {
			p := filepath.Join(dir, name)
			if err := os.WriteFile(p, b, 0o644); err != nil {
				return nil, err
			}
			sizes[p] = len(b)
		}
	}
	return sizes, nil
}

// encodeJSON is the §3.8 encoder: no HTML escaping, two-space indent, keys
// sorted (map keys are sorted by encoding/json; structs are declared in
// alphabetical order). The output ends with one newline.
func encodeJSON(v any) []byte {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(v); err != nil {
		panic(err)
	}
	return buf.Bytes()
}

const swiftHeader = "// Generated by `go run ./cmd/vectors` from docs/DESIGN.md §3.8; do not edit.\n\n"

// swiftLiteral wraps the JSON in extension KilitVectors { static let <name>:
// String = #\"\"\" … \"\"\"# }. The closing delimiter sits at column 0 so
// Swift strips no indentation; the literal excludes the final newline.
func swiftLiteral(name string, js []byte) []byte {
	var b strings.Builder
	b.WriteString(swiftHeader)
	b.WriteString("extension KilitVectors {\n")
	b.WriteString("    static let " + name + ": String = #\"\"\"\n")
	b.Write(bytes.TrimSuffix(js, []byte("\n")))
	b.WriteString("\n\"\"\"#\n}\n")
	return []byte(b.String())
}

// ---- shared helpers ----

// hx is the lowercase hex encoding of §3.9.
func hx(b []byte) string { return kc.HexString(b) }

// seedKey is the §3.8 key notation "pp…ll": first byte pp, last byte ll,
// zeros between.
func seedKey(prefix, last byte) []byte {
	b := make([]byte, 32)
	b[0] = prefix
	b[31] = last
	return b
}

func dup(b []byte) []byte { return append([]byte(nil), b...) }

func must[T any](v T, err error) T {
	if err != nil {
		panic(err)
	}
	return v
}

// expectErr panics unless err maps to the given Swift case name.
func expectErr(what string, err error, name string) {
	if got := kc.ErrorName(err); got != name {
		panic(fmt.Sprintf("%s: expected error %q, got %q (%v)", what, name, got, err))
	}
}

func expectEqual(what string, got, want []byte) {
	if !bytes.Equal(got, want) {
		panic(fmt.Sprintf("%s: got %x, want %x", what, got, want))
	}
}

// uuidSpelling renders 16 bytes as 8-4-4-4-12 hex.
func uuidSpelling(b []byte) string {
	x := hx(b[:16])
	return x[0:8] + "-" + x[8:12] + "-" + x[12:16] + "-" + x[16:20] + "-" + x[20:32]
}

// innerID is a deterministic uuid-shaped inner message id for a label.
func innerID(label string) string {
	h := sha256.Sum256([]byte("Kilit_vec_inner:" + label))
	return uuidSpelling(h[:])
}

// altMsgID derives a distinct outer msg_id for a redelivery of orig.
func altMsgID(orig string, k int) string {
	h := sha256.Sum256([]byte(fmt.Sprintf("Kilit_vec_redelivery:%s:%d", orig, k)))
	return hx(h[:16])
}

// mkskippedHash is the §3.8 hash form: SHA-256 over dh(32) || u32BE(n) ||
// mk(32) for all entries sorted by (dh bytes, n).
func mkskippedHash(keys []kc.SkippedKey) []byte {
	s := make([]kc.SkippedKey, len(keys))
	copy(s, keys)
	sort.Slice(s, func(i, j int) bool {
		if c := bytes.Compare(s[i].DHPub, s[j].DHPub); c != 0 {
			return c < 0
		}
		return s[i].N < s[j].N
	})
	h := sha256.New()
	for _, k := range s {
		h.Write(k.DHPub)
		h.Write(kc.U32BE(k.N))
		h.Write(k.MK)
	}
	return h.Sum(nil)
}

// hexOrNil renders an optional byte string (null when nil).
func hexOrNil(b []byte) any {
	if b == nil {
		return nil
	}
	return hx(b)
}

// stateDump is the STATE object of §3.9.
func stateDump(st *kc.State) map[string]any {
	m := map[string]any{
		"rk": hx(st.RK), "cks": hexOrNil(st.CKs), "ckr": hexOrNil(st.CKr),
		"ns": st.Ns, "nr": st.Nr, "pn": st.PN,
		"dhs_priv": hx(st.DHsPriv), "dhr": hexOrNil(st.DHr),
	}
	if len(st.MKSkipped) > 50 {
		m["mkskipped_count"] = len(st.MKSkipped)
		m["mkskipped_sha256"] = hx(mkskippedHash(st.MKSkipped))
		return m
	}
	list := make([]map[string]any, 0, len(st.MKSkipped))
	for _, k := range st.MKSkipped {
		list = append(list, map[string]any{"dh": hx(k.DHPub), "n": k.N, "mk": hx(k.MK)})
	}
	m["mkskipped"] = list
	return m
}

// padInner encodes and pads an inner message.
func padInner(m *kc.Inner) []byte {
	raw := must(kc.EncodeInner(m))
	return must(kc.Pad(raw))
}

func textInner(id, text string, ts int64) *kc.Inner {
	return &kc.Inner{T: kc.TText, ID: id, Ts: ts, Text: &text}
}
